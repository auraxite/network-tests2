#!/usr/bin/env python3
"""Шпаргалка для устного разговора о работе.

Это НЕ конференционный документ, поэтому шаблон abrau-2026 здесь не нужен:
берётся чистый docx со встроенными стилями и читаемой вёрсткой. Задача —
чтобы можно было быстро найти нужный абзац глазами во время разговора.
"""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt, RGBColor

OUT = Path(__file__).resolve().parent / "output" / "Шпора.docx"

ACCENT = RGBColor(0x1F, 0x4E, 0x79)


def setup(doc):
    s = doc.sections[0]
    s.top_margin = s.bottom_margin = Cm(1.8)
    s.left_margin = s.right_margin = Cm(2.0)
    n = doc.styles["Normal"]
    n.font.name = "Times New Roman"
    n.font.size = Pt(11)
    n.paragraph_format.space_after = Pt(6)
    n.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        r.font.color.rgb = ACCENT
        r.font.name = "Times New Roman"
    return p


def q(doc, question, answer):
    """Вопрос полужирным, ответ следом обычным."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(question)
    r.bold = True
    a = doc.add_paragraph(answer)
    a.paragraph_format.space_after = Pt(10)
    a.paragraph_format.left_indent = Cm(0.5)


def bullet(doc, text):
    p = doc.add_paragraph(text, style="List Bullet")
    p.paragraph_format.space_after = Pt(3)


def term(doc, name, meaning):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(name + " — ")
    r.bold = True
    p.add_run(meaning)


def build():
    doc = Document()
    setup(doc)

    t = doc.add_heading("Шпаргалка по работе: измерение задержек между GPU в кластере", 0)
    for r in t.runs:
        r.font.color.rgb = ACCENT
        r.font.name = "Times New Roman"
        r.font.size = Pt(18)

    # ------------------------------------------------------------------
    h(doc, "1. Суть работы в трёх фразах")
    doc.add_paragraph(
        "Мы измеряем, сколько времени занимает передача данных между двумя "
        "видеокартами в вычислительном кластере — внутри одного компьютера и "
        "между разными компьютерами. Для этого написана программа, которая "
        "прогоняет обмен через все пары видеокарт и строит таблицу задержек. "
        "Главный вывод: результат зависит не только от железа, но и от того, "
        "как настроена программная обвязка и как процессу выданы ресурсы, — "
        "поэтому эти условия надо фиксировать вместе с числами."
    )

    # ------------------------------------------------------------------
    h(doc, "2. Зачем это нужно")
    bullet(doc, "Суперкомпьютер считает на видеокартах, но им надо обмениваться "
                "промежуточными данными. Если обмен медленный, мощность карт не "
                "используется — обмен становится узким местом.")
    bullet(doc, "Кластер неоднороден: одни пары карт связаны быстро, другие "
                "медленно. Зная карту задержек, можно грамотнее раскладывать "
                "задачу по устройствам.")
    bullet(doc, "Нужен инструмент, который меряет это единообразно и "
                "воспроизводимо. Он и сделан.")

    # ------------------------------------------------------------------
    h(doc, "3. Словарь (если спросят, что это за слова)")
    term(doc, "GPU", "видеокарта, она же графический процессор; считает быстро, "
                     "но имеет свою отдельную память.")
    term(doc, "Узел", "один физический компьютер в кластере. Внутри него "
                      "несколько GPU.")
    term(doc, "MPI", "стандартная библиотека, через которую процессы на разных "
                     "узлах обмениваются сообщениями.")
    term(doc, "UCX", "транспортный слой под MPI: именно он решает, по какому "
                     "физическому пути реально поедут данные.")
    term(doc, "CUDA-aware MPI", "режим, в котором в MPI можно передать указатель "
                                "прямо на память видеокарты, не копируя её "
                                "содержимое в обычную память.")
    term(doc, "GPUDirect P2P / RDMA", "технологии NVIDIA: первая позволяет двум "
                                      "GPU внутри узла обмениваться напрямую, "
                                      "вторая — сетевой карте читать память GPU "
                                      "без участия процессора.")
    term(doc, "NVLink / NVSwitch", "быстрый фирменный канал между видеокартами. "
                                   "NVSwitch — коммутатор, через который каждая "
                                   "карта связана с каждой на полной скорости.")
    term(doc, "PCIe", "обычная системная шина, к которой подключены устройства. "
                      "Заметно медленнее NVLink.")
    term(doc, "InfiniBand", "быстрая сеть между узлами кластера.")
    term(doc, "NUMA", "у двухпроцессорной машины память разделена на области; "
                      "обращение к «своей» области быстрее, чем к «чужой».")
    term(doc, "Slurm", "планировщик: распределяет узлы, ядра и видеокарты между "
                       "задачами пользователей.")

    # ------------------------------------------------------------------
    h(doc, "4. Что именно сделано")
    bullet(doc, "Программа на C++ с CUDA и MPI. Запускается один процесс на одну "
                "видеокарту (раньше в проекте было по процессу на узел).")
    bullet(doc, "Два режима нагрузки: one_to_one — работает одна пара за раз, "
                "видно чистую скорость канала; all_to_all — все пары "
                "одновременно, видно поведение под нагрузкой.")
    bullet(doc, "Две среды передачи: auto — данные идут напрямую между GPU; "
                "host — данные принудительно копируются через обычную "
                "оперативную память. Сравнение показывает, что даёт прямой путь.")
    bullet(doc, "Результаты сохраняются в NetCDF, по ним строятся теплокарты "
                "задержек по всем парам и графики зависимости от размера "
                "сообщения.")
    bullet(doc, "Добавлена согласованная привязка ресурсов: видеокарта, сетевая "
                "карта и процессорные ядра выбираются так, чтобы находиться "
                "рядом физически.")

    # ------------------------------------------------------------------
    h(doc, "5. Как меряем и почему именно так")
    doc.add_paragraph(
        "Время засекается на стороне получателя: от момента, когда он готов "
        "принять данные, до момента, когда приём завершён. Так сделано потому, "
        "что отправитель и получатель — разные процессы на разных машинах, и "
        "их часы не синхронизированы; а у получателя достаточно одних "
        "локальных часов. Важная оговорка: в этот интервал может попасть "
        "ожидание, пока отправитель начнёт передавать, поэтому наши числа — "
        "оценка сверху."
    )
    doc.add_paragraph(
        "Каждый замер повторяется много раз. Сначала идёт прогрев без записи "
        "времени, затем измерительная серия. В качестве типичного значения "
        "берём медиану, а не среднее: единичные выбросы (например, чужая "
        "задача на узле) среднее портят, а медиану почти нет. По разбросу "
        "отдельных замеров считаем погрешность — чтобы понимать, настоящая "
        "разница между парами или это шум."
    )

    # ------------------------------------------------------------------
    h(doc, "6. Что получилось")
    bullet(doc, "Там, где видеокарты соединены через NVSwitch, прямой обмен "
                "примерно в семнадцать раз быстрее, чем через оперативную "
                "память, и выходит на три четверти теоретической скорости "
                "канала. Все пары карт дают одинаковый результат — это как раз "
                "и означает, что коммутатор связывает каждую с каждой.")
    bullet(doc, "Там, где карты подключены обычной шиной PCIe, выигрыш прямого "
                "обмена гораздо скромнее — упираемся в шину.")
    bullet(doc, "Между узлами прямой обмен тоже выигрывает и выходит примерно "
                "на три четверти предела сети InfiniBand.")
    bullet(doc, "Когда все пары обмениваются одновременно, задержки растут: "
                "передачи конкурируют за общие ресурсы, прежде всего за "
                "единственную сетевую карту узла.")

    # ------------------------------------------------------------------
    h(doc, "7. Вероятные вопросы и ответы")

    q(doc, "Чем это отличается от предыдущей работы по той же теме?",
      "Там был один процесс на узел, и среда передачи не была отдельным "
      "параметром. У нас процесс на каждую видеокарту, поэтому видно пары "
      "внутри узла, а способ передачи (напрямую или через память) задаётся "
      "явно и сравнивается.")

    q(doc, "Почему меряете у получателя, а не полное время от отправки до приёма?",
      "Потому что отправитель и получатель — разные процессы на разных машинах "
      "с несинхронизированными часами. Разность их показаний была бы "
      "недостоверна. У получателя хватает своих часов, а цена — что в интервал "
      "может попасть ожидание начала передачи. Мы честно пишем, что это оценка "
      "сверху.")

    q(doc, "Почему медиана, а не среднее?",
      "Кластер общий, на узлах идут чужие задачи. Редкий большой выброс сильно "
      "сдвигает среднее, а медиану почти нет. Для «типичного времени» медиана "
      "честнее.")

    q(doc, "Почему сравниваете именно на крупных сообщениях?",
      "На мелких сообщениях время почти целиком уходит на накладные расходы "
      "запуска обмена, и канал не видно. На крупных накладные расходы "
      "теряются, и задержка определяется пропускной способностью — то есть "
      "именно тем, что мы хотим измерить.")

    q(doc, "Почему три четверти, а не сто процентов от теоретической скорости?",
      "Теоретическая цифра — это физический предел линии без всяких "
      "накладных расходов. В реальности есть служебные заголовки протокола, "
      "согласование отправителя с получателем и синхронизация с видеокартой. "
      "Три четверти для обмена через MPI — нормальный результат.")

    q(doc, "Что такое привязка ресурсов и почему ей посвящён отдельный кусок?",
      "Процессу нужны три вещи: видеокарта, сетевая карта и процессорные ядра. "
      "Они расположены в машине физически в разных местах, и если выдать их "
      "несогласованно, данные поедут длинным путём. Опорная здесь видеокарта: "
      "её назначают по номеру процесса, а сетевую карту и ядра подбирают "
      "поближе к ней.")

    q(doc, "В чём была сложность с этой привязкой?",
      "Чтобы подобрать сетевую карту к видеокарте, надо знать свою видеокарту. "
      "А номер процесса внутри узла обычно узнают средствами MPI, то есть уже "
      "после его запуска — когда транспортный слой сетевую карту уже выбрал. "
      "Мы берём номер из переменных окружения планировщика, они доступны сразу, "
      "и успеваем выбрать всё до запуска MPI.")

    q(doc, "Почему нельзя напрямую сравнивать one_to_one и all_to_all?",
      "В режиме одной пары измеряется чистая передача. В режиме всех пар время "
      "завершения конкретной передачи зависит ещё и от того, в каком порядке "
      "транспортный слой обслуживал очередь запросов. Это разные величины, "
      "сравнивать их лоб в лоб некорректно.")

    q(doc, "Какие ограничения у работы?",
      "Точный физический маршрут пакета без прав администратора не проследить — "
      "мы судим о нём по косвенным признакам, прежде всего по измеренной "
      "скорости. Кроме того, кластер общий, и фоновые задачи вносят шум; "
      "частично это гасится медианой и прогревом.")

    q(doc, "Какая от этого практическая польза?",
      "Во-первых, инструмент показывает, где в кластере узкие места и какие "
      "пары устройств связаны хуже. Во-вторых, показано, что одни и те же "
      "настройки могут менять результат в разы, так что при публикации "
      "измерений их надо указывать — иначе числа несопоставимы.")

    q(doc, "Что дальше?",
      "Перенести измерения на конфигурацию, где на узле несколько сетевых "
      "карт: там выбор карты по близости к видеокарте должен дать заметный "
      "эффект, которого на текущем железе с одной картой увидеть нельзя.")

    # ------------------------------------------------------------------
    h(doc, "8. Если забыл всё остальное")
    doc.add_paragraph(
        "Написана программа, которая меряет скорость обмена между всеми парами "
        "видеокарт кластера в одинаковых условиях. Прямой обмен между картами "
        "заметно быстрее обмена через оперативную память — насколько именно, "
        "зависит от того, чем карты соединены. И главное: измеренная скорость "
        "сильно зависит от настроек и от того, как процессу выданы ресурсы, "
        "поэтому их надо фиксировать вместе с результатами."
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT))
    return OUT


if __name__ == "__main__":
    p = build()
    from docx import Document as D
    d = D(str(p))
    print(f"{p.name}: абзацев {len(d.paragraphs)}, "
          f"слов {sum(len(x.text.split()) for x in d.paragraphs)}")
