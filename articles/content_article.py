ABSTRACT_EN = (
    "Abstract. This work addresses the problem of measuring data transfer "
    "latency between graphics processing units (GPUs) in a computing cluster. "
    "When several GPUs are used, the data exchange speed between them, "
    "together with the computation speed, determines the overall performance, "
    "which makes latency measurement practically relevant. Measurements were "
    "performed for intra-node and inter-node GPU pairs while varying three "
    "parameters: message size, transfer environment, and testing mode. The "
    "transfer environment determines whether communication is performed "
    "directly between devices or through host memory. The testing mode defines "
    "the exchange "
    "scenario — an isolated transfer between a single pair of devices or a "
    "simultaneous exchange among all pairs. A software module was implemented "
    "that measures latency for all GPU pairs of the cluster under comparable "
    "conditions and builds latency-versus-message-size plots as well as "
    "heatmaps of latency distribution across GPU pairs. The measurements "
    "reveal differences between intra-node and inter-node transfers and "
    "quantify the influence of message size, transfer environment, and "
    "concurrent load on latency."
)

